// Writes src/lib/cip-series-labels.ts: the official title of every 4-digit
// CIP series ("11.07" → "Computer Science"), taken from the value set IPEDS
// ships for the completions table's CIPCODE column. A series is roughly what a
// student would call a major, finer than the 2-digit family in cip-labels.ts.
//
//   node scripts/gen-cip-labels.mjs ipeds_data/ipeds-cache/2024/IPEDS202425.accdb
//
// Rerun when CIP is revised (the 2020 edition is current); the year of the
// file does not otherwise matter.
import { readFileSync, writeFileSync } from "fs";
import MDBReader from "mdb-reader";

const accdb = process.argv[2];
if (!accdb) {
  console.error("usage: node scripts/gen-cip-labels.mjs <path to IPEDS .accdb>");
  process.exit(1);
}

const reader = new MDBReader(readFileSync(accdb));
const valueSets = reader.getTableNames().find((n) => /^valueSets\d+$/i.test(n));
if (!valueSets) throw new Error(`no valueSets table in ${accdb}`);

const labels = new Map();
for (const r of reader.getTable(valueSets).getData()) {
  if (!/^C\d{4}_A$/i.test(r.TableName) || r.VarName?.toUpperCase() !== "CIPCODE") continue;
  const code = String(r.Codevalue);
  if (/^\d{2}\.\d{2}$/.test(code)) labels.set(code, String(r.ValueLabel).trim());
}
if (labels.size === 0) throw new Error("no 4-digit CIPCODE labels found");

const lines = [...labels.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, label]) => `  "${code}": ${JSON.stringify(label)},`);

writeFileSync(
  "src/lib/cip-series-labels.ts",
  `// Generated by scripts/gen-cip-labels.mjs from IPEDS's CIPCODE value set — do not edit.
// 4-digit CIP series → official title (CIP 2020).
export const CIP_SERIES_LABELS: Record<string, string> = {
${lines.join("\n")}
};
`,
);
console.log(`wrote ${labels.size} CIP series labels`);
